from types import SimpleNamespace

import numpy as np
import pytest
import soundfile as sf
import torch

from conftest import TinyTokenizer
from src.emotion_checkpoint import PreprocessingConfig, prepare_audio
from src.iemocap_embedding_cache import build_cache, CachedDataset, collate_embeddings
from src.train_mvp_baseline import metrics_from_predictions


def test_frozen_cache_matches_raw_predictions_and_rejects_tampering(
    tiny_model, tmp_path
):
    samples = []
    for i, length in enumerate((1024, 1600)):
        path = tmp_path / f"audio{i}.wav"
        sf.write(
            path,
            np.linspace(-0.1, 0.1, length, dtype=np.float32),
            16000,
            subtype="FLOAT",
        )
        samples.append(
            SimpleNamespace(
                audio_path=str(path),
                text="hello there",
                label=i,
                session=1,
                utterance_id=f"Ses01F_example_F00{i}",
            )
        )
    model, tokenizer = tiny_model(), TinyTokenizer()
    cache = tmp_path / "cache"
    config = PreprocessingConfig()
    build_cache(samples, model, tokenizer, config, cache, "metadata", "cpu")
    original_index = (cache / "index.json").read_bytes()
    build_cache(samples, model, tokenizer, config, cache, "metadata", "cpu")
    assert (cache / "index.json").read_bytes() == original_index
    dataset = CachedDataset(samples, cache)
    text, tm, audio, am, _ = collate_embeddings([dataset[0], dataset[1]])
    with torch.inference_mode():
        cached = model.forward_from_embeddings(text, audio, tm, am).logits
        for i, sample in enumerate(samples):
            data, rate = sf.read(sample.audio_path, dtype="float32")
            tokens = tokenizer(sample.text)
            raw = model(
                tokens["input_ids"],
                tokens["attention_mask"],
                prepare_audio(data, rate, config)[None],
            ).logits
            torch.testing.assert_close(cached[i : i + 1], raw, atol=2e-6, rtol=2e-6)
    # Cache identity must include the source and generated bytes.
    (cache / f"{samples[0].utterance_id}.npz").write_bytes(b"corrupted")
    with pytest.raises(ValueError, match="checksum"):
        CachedDataset(samples, cache)


def test_development_cache_rejects_test_session(tiny_model, tmp_path):
    sample = SimpleNamespace(session=5)
    with pytest.raises(ValueError, match="Session 5"):
        build_cache(
            [sample],
            tiny_model(),
            TinyTokenizer(),
            PreprocessingConfig(),
            tmp_path,
            "metadata",
            "cpu",
        )


def test_macro_f1_keeps_all_four_classes():
    metrics = metrics_from_predictions([0, 1, 2, 3], [[1, 0, 0, 0]] * 4)
    assert metrics["accuracy"] == 0.25
    assert metrics["uar"] == 0.25
    assert metrics["macro_f1"] == 0.1
    assert len(metrics["confusion"]) == 4


def test_asr_abstention_counts_as_a_missed_label():
    from src.evaluate_asr_baseline import diagnostic_metrics

    rows = [{"label": i, "prediction": i if i < 3 else -1} for i in range(4)]
    metrics = diagnostic_metrics(rows)
    assert metrics["accuracy"] == metrics["macro_f1"] == metrics["uar"] == 0.75
    assert metrics["abstentions"] == 1
    assert np.sum(metrics["confusion_with_abstention_column"]) == 4
    assert metrics["confusion_with_abstention_column"][3][4] == 1
